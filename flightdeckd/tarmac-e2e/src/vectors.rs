//! Interop vectors: one handshake and a few sealed frames computed from fixed
//! "random" inputs, written to `vectors/handshake-v1.json`. The PWA's WebCrypto
//! code must reproduce every value (`vectors/check-webcrypto.mjs`), so any
//! drift between the Rust and the JavaScript side of the contract fails a test.
//!
//! `TARMAC_E2E_WRITE_VECTORS=1 cargo test` rewrites the file after a deliberate
//! contract change; otherwise the test only compares.

#![allow(deprecated)] // ring's fixed-output RNG: the only way to pin ephemerals

use std::cell::UnsafeCell;

use ring::test::rand::FixedSliceSequenceRandom;
use serde_json::{json, Value};

use crate::b64;
use crate::handshake::{node_accept, PhoneHandshake};
use crate::keys::{DeviceId, DeviceSecret};
use crate::LABEL;

const VECTORS: &str = include_str!("../vectors/handshake-v1.json");
const PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/vectors/handshake-v1.json");

fn seq<'a>(bytes: &'a [&'a [u8]]) -> FixedSliceSequenceRandom<'a> {
    FixedSliceSequenceRandom { bytes, current: UnsafeCell::new(0) }
}

fn build() -> Value {
    let mac_id = "6f0c3a9e-9b1d-4c47-8f4e-1d2a3b4c5d6e";
    let device_id = DeviceId::from_bytes(*b"tarmac-device-01");
    let secret = DeviceSecret::from_bytes(*b"tarmac e2e vector device secret!");
    let node_key = secret.node_key(mac_id);
    // Valid P-256 scalars (well below the group order).
    let phone_seed = [0x31u8; 32];
    let phone_nonce = [0xa1u8; 16];
    let node_seed = [0x42u8; 32];
    let node_nonce = [0xb2u8; 16];

    let (phone_hs, hello) = {
        let inputs: [&[u8]; 2] = [&phone_seed, &phone_nonce];
        let rng = seq(&inputs);
        PhoneHandshake::start(device_id, 3, &rng).unwrap()
    };
    let (accept, mut node) = {
        let inputs: [&[u8]; 2] = [&node_seed, &node_nonce];
        let rng = seq(&inputs);
        node_accept(&hello, mac_id, &node_key, &rng).unwrap()
    };
    let mut phone = phone_hs.finish(&accept, mac_id, &node_key).unwrap();

    let up = [
        json!({"type": "subscribe"}),
        json!({"type": "rpc", "id": "r1", "method": "send_message",
               "params": {"conversation_id": "c-1", "text": "héllo ✈️"}}),
    ];
    let down = [
        json!({"type": "ready", "label": "MacBook Pro"}),
        json!({"type": "rpc_result", "id": "r1", "result": {"conversation_id": "c-1", "delivered": true}}),
    ];
    let mut frames = Vec::new();
    for (u, d) in up.iter().zip(down.iter()) {
        let plain = u.to_string();
        let sealed = phone.seal(plain.as_bytes()).unwrap();
        assert_eq!(node.open(&sealed).unwrap(), plain.as_bytes());
        frames.push(json!({"dir": "up", "plaintext": plain, "frame": sealed.to_frame()}));
        let plain = d.to_string();
        let sealed = node.seal(plain.as_bytes()).unwrap();
        assert_eq!(phone.open(&sealed).unwrap(), plain.as_bytes());
        frames.push(json!({"dir": "down", "plaintext": plain, "frame": sealed.to_frame()}));
    }

    json!({
        "label": LABEL,
        "comment": "Generated by tarmac-e2e (src/vectors.rs). Fixed inputs; every other value must be reproduced by any implementation of docs/tarmac-sealed-channel.md.",
        "mac_id": mac_id,
        "device_id": device_id.to_b64(),
        "generation": 3,
        "device_secret": secret.to_b64(),
        "node_key": node_key.to_b64(),
        "phone_ephemeral_private": b64::encode(&phone_seed),
        "node_ephemeral_private": b64::encode(&node_seed),
        "hello": hello.to_frame(),
        "accept": accept.to_frame(),
        "frames": frames,
        "push": push_vector(mac_id, &node_key),
    })
}

/// A node-signed push (§8): the push key, the exact signed bytes and the payload.
fn push_vector(mac_id: &str, node_key: &crate::keys::NodeKey) -> Value {
    use crate::push::{push_key, push_signed_bytes, signed_payload, PushSigner, PushState};
    let event = json!({"kind": "needs_attention", "conversationId": "c-1", "text": "Approve ✈️ deploy?"});
    let payload =
        signed_payload(mac_id, &event, PushState::Question, PushSigner { generation: 3, key: node_key }, 1_800_000_000_000, "cHVzaC1pZC0x");
    json!({
        "push_key": b64::encode(&push_key(node_key)),
        "signed_bytes": b64::encode(&push_signed_bytes(&payload)),
        "payload": payload,
    })
}

#[test]
fn interop_vectors_are_current() {
    let fresh = serde_json::to_string_pretty(&build()).unwrap() + "\n";
    if std::env::var_os("TARMAC_E2E_WRITE_VECTORS").is_some() {
        std::fs::write(PATH, &fresh).unwrap();
        return;
    }
    assert_eq!(
        VECTORS, fresh,
        "vectors/handshake-v1.json is stale: a byte of the contract changed. If that was \
         deliberate, rerun with TARMAC_E2E_WRITE_VECTORS=1 and update every other implementation."
    );
}
