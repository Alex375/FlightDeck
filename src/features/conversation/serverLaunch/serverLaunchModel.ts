// The server launch, as plain data: its steps and what each one says when it is done, when the
// invite above the composer shows, and how the copy report reads. Pure — the store
// (serverLaunchStore.ts) drives the steps, the components render this.

import type { CopyOutcome, CopyWhy, ServerFacts, SkipWhy, TransferOutcome, WorktreeOutcome } from "../../../ipc/client";
import { MACHINE } from "../../../ui/platform";

export type LaunchStepId = "check" | "transfer" | "copy" | "worktree" | "start";

/** The steps, in order — the preparation screen lists every one of them from the start. */
export const LAUNCH_STEPS: readonly { id: LaunchStepId; label: string }[] = [
  { id: "check", label: "Check the link and align the server" },
  { id: "transfer", label: "Transfer the repository" },
  { id: "copy", label: "Copy the uncommitted files" },
  { id: "worktree", label: "Create the worktree" },
  { id: "start", label: "Start the conversation" },
];

export type StepStatus = "pending" | "running" | "done" | "failed";

export interface StepState {
  status: StepStatus;
  /** What the step found, once done (or what it is doing). */
  detail: string | null;
  /** Why it failed — a full sentence from the core. */
  error: string | null;
}

export function freshSteps(): Record<LaunchStepId, StepState> {
  const out = {} as Record<LaunchStepId, StepState>;
  for (const s of LAUNCH_STEPS) out[s.id] = { status: "pending", detail: null, error: null };
  return out;
}

/** The first step not done yet — where a run (or a retry) picks up. `null` once all are. */
export function nextStep(steps: Record<LaunchStepId, StepState>): LaunchStepId | null {
  return LAUNCH_STEPS.find((s) => steps[s.id].status !== "done")?.id ?? null;
}

/** The step that failed, if one did. */
export function failedStep(steps: Record<LaunchStepId, StepState>): LaunchStepId | null {
  return LAUNCH_STEPS.find((s) => steps[s.id].status === "failed")?.id ?? null;
}

/** Whether the invite to run a new conversation on a server shows. */
export function inviteVisible(c: {
  pref: boolean;
  kind: "claude" | "codex";
  /** Its folder is on this Mac. */
  local: boolean;
  /** Never started: no session, no live process, nothing in the thread. */
  empty: boolean;
  /** A launch is already running or finished for it. */
  launching: boolean;
  /** Dismissed for this conversation. */
  dismissed: boolean;
  /** Paired servers. */
  servers: number;
}): boolean {
  return c.pref && c.kind === "claude" && c.local && c.empty && !c.launching && !c.dismissed && c.servers > 0;
}

export function formatBytes(n: number): string {
  if (n < 1024) return `${n} B`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(n < 10 * 1024 ? 1 : 0)} KiB`;
  if (n < 1024 * 1024 * 1024) return `${(n / (1024 * 1024)).toFixed(1)} MiB`;
  return `${(n / (1024 * 1024 * 1024)).toFixed(2)} GiB`;
}

export function checkDetail(f: ServerFacts): string {
  const where = [f.os, f.user ? `user ${f.user}` : null, f.git.replace(/^git version /, "git ")].filter(Boolean).join(" · ");
  // The alignment entry point (task 763ae7f2) is not wired yet: say what was really done.
  return f.aligned ? `${where} · aligned` : `${where} · link checked`;
}

export function transferDetail(t: TransferOutcome): string {
  const at = `${t.local.branch ?? "detached HEAD"} @ ${t.local.commit.slice(0, 7)}`;
  const sent = t.bundleBytes > 0 ? `${formatBytes(t.bundleBytes)} of commits sent` : "the server already had every commit";
  const unpushed = t.local.unpushed ? ` · ${t.local.unpushed} not pushed` : "";
  return `${at}${unpushed} · ${sent} · ${t.created ? "new clone" : "clone reused"}`;
}

export function copyDetail(c: CopyOutcome): string {
  const parts: string[] = [];
  if (c.staged) parts.push(`${c.staged} staged`);
  if (c.unstaged) parts.push(`${c.unstaged} unstaged`);
  parts.push(`${c.copied.length} file${c.copied.length === 1 ? "" : "s"} copied`);
  const left = c.skipped.length + c.skippedMore;
  if (left) parts.push(`${left} left behind`);
  return parts.join(" · ");
}

export function worktreeDetail(w: WorktreeOutcome): string {
  return `${w.branch ? `branch ${w.branch}` : "detached"} · ${w.worktree}`;
}

export const COPY_WHY_LABEL: Record<CopyWhy, string> = {
  untracked: "untracked",
  claude: "Claude",
  secret: "secret",
};

export const SKIP_WHY_LABEL: Record<SkipWhy, string> = {
  regenerable: "regenerated by an install or a build",
  ignored: "ignored by git",
  tooLarge: "too large",
  worktrees: `this ${MACHINE}'s worktrees`,
  notAFile: "not a regular file",
  unscanned: "too large to look through",
  overBudget: "over the copy's size limit",
};

/** The "left behind" entries grouped by reason, most telling first. */
export function skippedByReason(c: CopyOutcome): { why: SkipWhy; label: string; paths: string[] }[] {
  const order: SkipWhy[] = ["tooLarge", "overBudget", "unscanned", "regenerable", "worktrees", "ignored", "notAFile"];
  return order
    .map((why) => ({ why, label: SKIP_WHY_LABEL[why], paths: c.skipped.filter((s) => s.why === why).map((s) => s.path) }))
    .filter((g) => g.paths.length > 0);
}

/** A progress fraction in [0, 1], or `null` without a total. */
export function progressFraction(sent: number, total: number): number | null {
  if (!(total > 0)) return null;
  return Math.max(0, Math.min(1, sent / total));
}
